                            <p>
                                Rather than letting the club fade, our committee and members rallied together to rebuild brick by
                                brick. In 2025, Andy Hay made a welcome return as Head Coach and Junior Lead. We re-established
                                structured <a href="/juniors">junior coaching</a>, introduced brand-new
                                dedicated Women's Coaching sessions, and expanded our competitive setup to four squash teams as well
                                as introducing a dedicated Squash 57 / Racketball team to welcome even more racket sports players.
                            </p>
                            <p>
                                The revival bore immediate fruit in 2026, when Sutton Squash Club proudly brought home silverware
                                by winning the Nottinghamshire County Cup (B Grade).
                            </p>
