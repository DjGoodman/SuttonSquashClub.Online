                            <p class="mb-0">
                                When the COVID-19 pandemic hit, courts across the country went silent. Returning to action
                                post-lockdown brought tough challenges: long-time coach and administrator Andy Hay stepped down
                                after years of invaluable service and dedication to growing the club. Active membership contracted
                                to just 20 adults and 5 juniors, and our representation dropped to two league teams.
                            </p>
