                            <p>
                                With official affiliation came rapid expansion. The club grew into a thriving community of over
                                75 members—including 40 passionate juniors and 35 adults—and fielded three competitive league teams.
                            </p>
                            <p class="mb-0">
                                When the original Sutton Centre closed its doors, the club entered a brief hiatus from league play
                                between 2008 and 2014. As the brand-new Lammas Leisure Centre opened, Sutton Squash Club made a
                                triumphant return to the Nottinghamshire League in 2014. The hard work paid off in 2019, when our
                                First Team achieved a landmark milestone by earning promotion to the Premier Division to compete
                                against the top talent in the county.
                            </p>
